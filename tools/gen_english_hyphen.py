"""中文：将固定TeX英语断词数据转换为只读紧凑Trie。/ English: Compile pinned TeX English patterns into a compact read-only trie."""
from pathlib import Path
import argparse,hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'tools/data/hyphen-en-us'
OUTPUT=ROOT/'main/book/english_hyphen_patterns.h'

def source_patterns():
    raw=(DATA/'hyph-en-us.tex').read_bytes();meta=json.loads((DATA/'provenance.json').read_text())
    if hashlib.sha256(raw).hexdigest()!=meta['sha256']:raise ValueError('Pinned hyphenation source changed')
    source=re.sub(r'%[^\n]*','',raw.decode('ascii'))
    patterns=re.search(r'\\patterns\s*\{([^}]*)\}',source,re.S)[1].split()
    exceptions=re.search(r'\\hyphenation\s*\{([^}]*)\}',source,re.S)[1].split()
    return patterns,exceptions,meta

def compile_header():
    patterns,exceptions,meta=source_patterns();trie={'children':{},'values':()}
    for pattern in patterns:
        if not re.fullmatch(r'[a-z.0-9]+',pattern):raise ValueError(pattern)
        letters='';values=[0]
        for c in pattern:
            if c.isdigit():values[-1]=int(c)
            else:letters+=c;values.append(0)
        node=trie
        for c in letters:node=node['children'].setdefault(c,{'children':{},'values':()})
        if node['values']:values=[max(a,b) for a,b in zip(node['values'],values)]
        node['values']=tuple(values)
    nodes=[(0,trie)];rows=[];values=[0];value_offsets={():0}
    for char,node in nodes:
        first=len(nodes) if node['children'] else 0
        for c,child in sorted(node['children'].items()):nodes.append((ord(c),child))
        v=node['values']
        if v not in value_offsets:value_offsets[v]=len(values);values.extend((len(v),*v))
        rows.append((first,value_offsets[v],len(node['children']),char))
    assert len(rows)<65536 and len(values)<65536
    notice='''/* Generated by tools/gen_english_hyphen.py; do not edit.\n * TeX en-US patterns: Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken.\n * Copying and distribution of this file, with or without modification,\n * are permitted in any medium without royalty provided the copyright\n * notice and this notice are preserved.\n * Source and pinned SHA: tools/data/hyphen-en-us/provenance.json\n */\n#pragma once\n'''
    out=notice+'typedef struct { uint16_t first, value; uint8_t count, letter; } english_hyphen_node_t;\n'
    out+='static const english_hyphen_node_t english_hyphen_nodes[] = {\n'
    for i in range(0,len(rows),8):out+=' '+','.join('{'+','.join(map(str,row))+'}' for row in rows[i:i+8])+',\n'
    out+='};\nstatic const uint8_t english_hyphen_values[] = {\n'
    for i in range(0,len(values),32):out+=' '+','.join(map(str,values[i:i+32]))+',\n'
    out+='};\ntypedef struct { const char *word; uint64_t points; } english_hyphen_exception_t;\nstatic const english_hyphen_exception_t english_hyphen_exceptions[] = {\n'
    for item in exceptions:
        word=item.replace('-','');mask=0;n=0
        for c in item:
            if c=='-':mask|=1<<n
            else:n+=1
        out+=' {"'+word+'", UINT64_C('+str(mask)+')},\n'
    out+='};\n'
    return out,{'patterns':len(patterns),'nodes':len(rows),'values_bytes':len(values),'table_bytes':6*len(rows)+len(values),'source_sha256':meta['sha256']}

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    text,stats=compile_header()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=text:raise SystemExit('Generated English hyphenation table is stale')
    else:OUTPUT.write_text(text)
    print(json.dumps(stats))
if __name__=='__main__':main()
